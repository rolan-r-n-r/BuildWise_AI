def vertex_xy(v: Any) -> Tuple[float, float]:
    if hasattr(v, "x") and hasattr(v, "y"):
        return float(v.x), float(v.y)
    if isinstance(v, (tuple, list)) and len(v) >= 2:
        return float(v[0]), float(v[1])
    return 0.0, 0.0


def polygon_of(points: Sequence[Sequence[float]]) -> Polygon:
    if not points or len(points) < 3:
        return Polygon()
    try:
        poly = Polygon([(float(x), float(y)) for x, y in points])
        if not poly.is_valid:
            poly = poly.buffer(0)
        return poly
    except Exception:
        return Polygon()


def safe_area(geom: Any) -> float:
    try:
        return float(geom.area) if geom is not None and not geom.is_empty else 0.0
    except Exception:
        return 0.0


def safe_union(geoms: Sequence[Any]) -> Any:
    usable = [g for g in geoms if g is not None and not g.is_empty]
    if not usable:
        return Polygon()
    return unary_union(usable)


def room_poly(room: Any, ox: float, oy: float) -> Polygon:
    return box(room.x + ox, room.y + oy,
               room.x + room.width_m + ox, room.y + room.depth_m + oy)


def footprint_polys(site: Any) -> Tuple[Polygon, Polygon, Polygon, float, Polygon]:
    """(declared plate, physical plate, bbox rectangle, declared area, link corridors).

    Since the declared plate is the PHYSICAL plate: wings plus their
    link corridors.  Counting wings only made a legitimate connector read as a
    room outside the plate and let LAND-07 furnish it as a dead store; the two
    geometries are therefore kept equal here and ``footprint.area_sqm`` agrees
    with them.
    """
    fp = site.footprint
    wings: List[Polygon] = []
    for wing in getattr(fp, "wings", []) or []:
        wings.append(box(wing.x, wing.y, wing.x + wing.width_m, wing.y + wing.depth_m))
    physical_parts = list(wings)
    for corr in getattr(fp, "corridors", []) or []:
        poly = polygon_of(getattr(corr, "polygon_coords", []) or [])
        if not poly.is_empty:
            physical_parts.append(poly)
    declared = safe_union(physical_parts) if physical_parts else box(fp.x, fp.y, fp.x + fp.width_m, fp.y + fp.depth_m)
    physical = declared
    corridors = safe_union([
        poly for poly in (polygon_of(getattr(c, "polygon_coords", []) or [])
                          for c in getattr(fp, "corridors", []) or [])
        if not poly.is_empty
    ]) if getattr(fp, "corridors", None) else Polygon()
    bbox = box(fp.x, fp.y, fp.x + fp.width_m, fp.y + fp.depth_m)
    return declared, physical, bbox, float(fp.area_sqm), corridors


def is_auto_label(name: str) -> bool:
    low = (name or "").strip().lower()
    return low.startswith(AUTO_LABEL_PREFIXES)


def aspect_of(width: float, depth: float) -> float:
    w, d = max(float(width), 1e-6), max(float(depth), 1e-6)
    return max(w, d) / min(w, d)


def spec_for(room: Any) -> Any:
    sid = getattr(room, "space_type_id", None)
    if sid:
        spec = ONTOLOGY.get_space(sid)
        if spec is not None and spec.id == sid:
            return spec
    ident = getattr(room, "identity", None)
    if ident is not None and getattr(ident, "space_type_id", None):
        return ONTOLOGY.get_space(ident.space_type_id)
    return None


def item_inside_room(item: Any, room: Any) -> bool:
    tol = 0.02
    return (
        item.x >= room.x - tol
        and item.y >= room.y - tol
        and item.x + item.width_m <= room.x + room.width_m + tol
        and item.y + item.depth_m <= room.y + room.depth_m + tol
    )


def furniture_assessment(room: Any) -> Tuple[Optional[bool], Optional[bool], Optional[bool], List[str]]:
    """(engine_ok, geometry_ok, combined_ok, reasons) for one room."""
    set_items = furniture_set_for(getattr(room, "space_type_id", None), room.room_id)
    if not set_items:
        return None, None, None, []
    # Circulation/terrace rooms are furnished only when the set is a furnishing
    # (a foyer does not need a bed).  Missing there is not a fit failure.
    if not room.furniture and room.zone_category in ("circulation", "terrace"):
        return None, None, None, []
    reasons: List[str] = []
    engine_ok = bool(room.furniture) and all(i.is_satisfied for i in room.furniture)
    if not room.furniture:
        reasons.append("no_furniture_placed")
    elif not engine_ok:
        reasons.append("engine_item_unsatisfied")
    inside = all(item_inside_room(i, room) for i in room.furniture)
    if room.furniture and not inside:
        reasons.append("item_outside_room")
    try:
        geom_ok = bool(
            layout_room(room.width_m, room.depth_m, set_items).satisfied
            or layout_room(room.depth_m, room.width_m, set_items).satisfied
        )
    except Exception:
        geom_ok = False
    if not geom_ok:
        reasons.append("set_does_not_fit")
    return engine_ok, geom_ok, bool(engine_ok and geom_ok and inside), reasons


def fixture_assessment(room: Any) -> Optional[bool]:
    if not room.fixtures:
        return None
    if any(not fx.is_satisfied for fx in room.fixtures):
        return False
    return all(item_inside_room(fx, room) for fx in room.fixtures)


