def build_request(plot: Dict[str, Any], typology_raw: str, floors: int) -> FloorPlanRequest:
    kwargs: Dict[str, Any] = dict(
        plot_width_m=plot["width"],
        plot_depth_m=plot["depth"],
        building_typology=typology_raw,
        floors=floors,
        ground_coverage_ratio=0.60,
        vastu_strictness="high",
        bypass_cache=True,
        ai_provider="mock",
        seed="42",
    )
    if plot["polygon"]:
        verts = plot["polygon"]
        xs = [p[0] for p in verts]
        ys = [p[1] for p in verts]
        kwargs["plot_polygon"] = PlotPolygonModel(
            vertices=verts,
            shape_type=plot["shape_type"],
            has_curved_edges=plot["has_curved_edges"],
            is_regular_rectangle=False,
            area_sqm=plot["area"],
            perimeter_m=0.0,
            bounding_box=(min(xs), min(ys), max(xs), max(ys)),
        )
    return FloorPlanRequest(**kwargs)


def measure(case: Dict[str, Any], resp: Any) -> Dict[str, Any]:
    row: Dict[str, Any] = {
        "case_id": case["case_id"],
        "plot": case["plot"],
        "typology": case["typology"],
        "floors": case["floors"],
        "status": resp.status,
        "gate_status": None,
        "generation_id": resp.generation_id,
        "warning_count": len(resp.warnings or []),
    }
    ms = resp.multi_storey
    site = resp.site_plan
    if ms is None:
        row["error"] = "no multi_storey"
        row["warnings_sample"] = (resp.warnings or [])[:4]
        return row

    row["gate_status"] = (ms.validation_gate or {}).get("overall_status")
    row["gate_layers"] = {l.get("layer_id"): l.get("status") for l in ((ms.validation_gate or {}).get("layers") or [])}
    rooms_by_floor = ms.floors
    all_rooms = [r for f in rooms_by_floor for r in f.rooms]
    row["room_count"] = len(all_rooms)
    row["gfa_sqm"] = round(sum(r.area_sqm for r in all_rooms if r.zone_category != "terrace"), 2)

    if site is None:
        row["land_missing"] = True
        row["warnings_sample"] = (resp.warnings or [])[:4]
        records = [
            room_record(case, room, floor.floor_index, 0.0, 0.0, None, None, 0)
            for floor in rooms_by_floor for room in floor.rooms
        ]
        row["rooms"] = records
        attach_room_aggregates(row, records)
        return row

    buildable = polygon_of(site.buildable_polygon_coords)
    declared_fp, physical_fp, bbox_fp, declared_area, corridor_fp = footprint_polys(site)
    wing_count = len(getattr(site.footprint, "wings", []) or [])
    ox = float(site.footprint.x)
    oy = float(site.footprint.y)
    buildable_area = float(site.buildable_area_sqm)
    plot_area = float(site.plot_polygon.area_sqm)

    # ---- surplus routing ---------------------------------------------------
    legend_out = [(o.name, safe_area(polygon_of(o.polygon_coords)), polygon_of(o.polygon_coords))
                  for o in (site.outdoor_zones or [])]
    legend_wedge = [(w.name, safe_area(polygon_of(w.polygon_coords)), polygon_of(w.polygon_coords))
                    for w in (site.wedge_zones or [])]
    designated = [p for name, area, p in legend_out + legend_wedge
                  if not is_auto_label(name) and not p.is_empty]
    auto = [p for name, area, p in legend_out + legend_wedge
            if is_auto_label(name) and not p.is_empty]
    outdoor_named = [p for name, area, p in legend_out if not is_auto_label(name) and not p.is_empty]
    outdoor_auto = [p for name, area, p in legend_out if is_auto_label(name) and not p.is_empty]

    residual = buildable.difference(declared_fp) if buildable.is_valid and declared_fp.is_valid else Polygon()
    designated_on_res = safe_union(designated).intersection(residual)
    auto_on_res = safe_union(auto).intersection(residual)
    unnamed_on_res = residual.difference(safe_union(designated + auto))
    surplus = safe_area(residual)

    row.update({
        "plot_area_sqm": round(plot_area, 2),
        "buildable_area_sqm": round(buildable_area, 2),
        "footprint_declared_sqm": round(declared_area, 2),
        "footprint_geom_sqm": round(safe_area(physical_fp), 2),
        "footprint_source": getattr(resp.land_economics, "footprint_source", None) if resp.land_economics else None,
        "program_needed_sqm": round(float(getattr(resp.land_economics, "program_needed_area_m2", 0.0) or 0.0), 2),
        "footprint_stretch_sqm": round(max(0.0, declared_area - float(getattr(resp.land_economics, "program_needed_area_m2", 0.0) or 0.0)), 2),
        "stretch_factor": round(declared_area / max(float(getattr(resp.land_economics, "program_needed_area_m2", 0.0) or 0.0), 0.01), 2),
        "upgrade_absorption_sqm": 0.0,
        "surplus_sqm": round(surplus, 2),
        "surplus_pct_buildable": round(100.0 * surplus / max(buildable_area, 0.01), 1),
        "outdoor_designated_sqm": round(safe_area(designated_on_res), 2),
        "outdoor_auto_sqm": round(safe_area(auto_on_res), 2),
        "outdoor_unnamed_sqm": round(safe_area(unnamed_on_res), 2),
        "outdoor_named_patch_count": len(outdoor_named),
        "outdoor_auto_patch_count": len(outdoor_auto),
        "outdoor_wedge_auto_count": len([1 for name, _, _ in legend_wedge if is_auto_label(name)]),
        "envelope_bbox_area_sqm": round(safe_area(bbox_fp), 2),
        "envelope_bbox_void_sqm": round(max(0.0, safe_area(bbox_fp) - safe_area(physical_fp)), 2),
        "footprint_outside_buildable_sqm": round(
            safe_area(physical_fp.difference(buildable)) if physical_fp.is_valid and buildable.is_valid else 0.0, 2
        ),
    })

    # ---- per-floor / per-room ---------------------------------------------
    room_records: List[Dict[str, Any]] = []
    void_by_floor: List[float] = []
    void_small = 0.0
    rooms_outside_fp_by_floor: List[float] = []
    rooms_outside_build_by_floor: List[float] = []
    ground_rooms_area = 0.0

    for floor in rooms_by_floor:
        floor_rooms = floor.rooms
        room_union = safe_union([room_poly(r, ox, oy) for r in floor_rooms])
        # A wing link corridor is declared circulation, not an unassigned void:
        # it is plate that serves the plan without being a catalogue room.
        void = (
            declared_fp.difference(room_union).difference(corridor_fp)
            if declared_fp.is_valid else Polygon()
        )
        void_parts = [g for g in getattr(void, "geoms", [void]) if safe_area(g) >= 1.0]
        void_small += sum(safe_area(g) for g in getattr(void, "geoms", [void]) if 0.0 < safe_area(g) < 1.0)
        void_by_floor.append(round(sum(safe_area(g) for g in void_parts), 2))

        fp_out = room_union.difference(declared_fp) if declared_fp.is_valid else Polygon()
        bl_out = room_union.difference(buildable) if buildable.is_valid else Polygon()
        rooms_outside_fp_by_floor.append(round(safe_area(fp_out), 2))
        rooms_outside_build_by_floor.append(round(safe_area(bl_out), 2))

        if floor.floor_index == 0:
            ground_rooms_area = sum(
                r.area_sqm for r in floor_rooms if r.zone_category != "terrace"
            )
        for room in floor_rooms:
            room_records.append(room_record(case, room, floor.floor_index, ox, oy,
                                            buildable, declared_fp, wing_count))

    row["plate_void_sqm"] = round(max(void_by_floor) if void_by_floor else 0.0, 2)
    row["plate_void_any_floor_sqm"] = round(sum(void_by_floor), 2)
    row["plate_void_by_floor"] = void_by_floor
    row["plate_void_sub1_sqm"] = round(void_small, 2)
    row["rooms_outside_fp_by_floor"] = rooms_outside_fp_by_floor
    row["rooms_outside_footprint_sqm"] = round(max(rooms_outside_fp_by_floor) if rooms_outside_fp_by_floor else 0.0, 2)
    row["rooms_outside_buildable_sqm"] = round(max(rooms_outside_build_by_floor) if rooms_outside_build_by_floor else 0.0, 2)
    row["ground_room_area_sqm"] = round(ground_rooms_area, 2)
    row["ground_plate_slack_sqm"] = round(max(0.0, declared_area - ground_rooms_area), 2)
    # LAND-07 absorbs dead corners by growing a room into them; the void is
    # therefore zero on the floor it repaired, not zero in the design.
    _abs = [float(x) for x in re.findall(r"LAND-07 Absorbed ([0-9.]+) m", " ".join(resp.warnings or []))]
    row["land07_absorbed_sqm"] = round(sum(_abs), 2)
    row["plate_void_ground_before_repair_sqm"] = round(
        (void_by_floor[0] if void_by_floor else 0.0) + sum(_abs), 2
    )

    row["rooms"] = room_records
    row["upgrade_absorption_sqm"] = round(sum(
        r["area_sqm"] for r in room_records
        if "PROP-LADDER-01" in (r.get("applied_rules") or [])
    ), 2)
    attach_room_aggregates(row, room_records)
    row["warnings_sample"] = (resp.warnings or [])[:4]
    return row


def attach_room_aggregates(row: Dict[str, Any], room_records: List[Dict[str, Any]]) -> None:
    """Aspect/area/furniture aggregates; works with or without a site plan."""
    measurable = [r for r in room_records if r.get("span_class")]
    over = [r for r in room_records if r.get("aspect_ok") is False]
    below_area = [r for r in room_records if r.get("area_ok") is False]
    below_width = [r for r in room_records if r.get("width_ok") is False]
    furnished = [r for r in room_records if r.get("furniture_ok") is not None]
    fixtures = [r for r in room_records if r.get("fixture_ok") is not None]
    row["aspect_max"] = round(max((r["aspect"] for r in measurable), default=0.0), 2)
    row["aspect_worst_room"] = max(measurable, key=lambda r: r["aspect"])["room_id"] if measurable else None
    row["aspect_over_band_count"] = len(over)
    row["aspect_over_band_pct"] = round(100.0 * len(over) / max(len(measurable), 1), 1)
    row["aspect_extreme_count"] = sum(1 for r in measurable if r["aspect"] >= 4.0)
    row["aspect_median"] = round(statistics.median([r["aspect"] for r in measurable]), 2) if measurable else None
    row["area_below_min_count"] = len(below_area)
    row["width_below_min_count"] = len(below_width)
    row["furniture_fit_pct"] = (
        round(100.0 * sum(1 for r in furnished if r["furniture_ok"]) / len(furnished), 1)
        if furnished else None
    )
    row["fixture_fit_pct"] = (
        round(100.0 * sum(1 for r in fixtures if r["fixture_ok"]) / len(fixtures), 1)
        if fixtures else None
    )
    row["furniture_room_count"] = len(furnished)
    row["fixture_room_count"] = len(fixtures)
    row["absorbed_room_count"] = sum(1 for r in room_records if r.get("absorbed"))
    row["absorbed_room_area_sqm"] = round(sum(r["area_sqm"] for r in room_records if r.get("absorbed")), 2)
    row["stored_aspect_mismatch_count"] = sum(1 for r in room_records if r.get("stored_aspect_mismatch"))
    row["pass_but_violates_proportion"] = bool(
        row.get("gate_status") == "PASS"
        and (row.get("aspect_over_band_count", 0) or row.get("area_below_min_count", 0)
             or row.get("width_below_min_count", 0))
    )


def room_record(case: Dict[str, Any], room: Any, floor: int, ox: float, oy: float,
                buildable: Optional[Polygon], declared_fp: Optional[Polygon],
                wings: int) -> Dict[str, Any]:
    spec = spec_for(room)
    width = float(room.width_m)
    depth = float(room.depth_m)
    aspect = round(aspect_of(width, depth), 2)
    min_area = float(getattr(spec, "min_area_sqm", 0.0) or 0.0) if spec else None
    min_width = float(getattr(spec, "min_width_m", 0.0) or 0.0) if spec else None
    band = float(getattr(spec, "max_aspect_ratio", 0.0) or 0.0) if spec else None
    engine_ok, geo_ok, furniture_ok, furn_reasons = furniture_assessment(room)
    fixture_ok = fixture_assessment(room)

    out_build = 0.0
    out_fp = 0.0
    if buildable is not None or declared_fp is not None:
        poly = room_poly(room, ox, oy)
        if buildable is not None and buildable.is_valid:
            out_build = safe_area(poly.difference(buildable))
        if declared_fp is not None and declared_fp.is_valid:
            out_fp = safe_area(poly.difference(declared_fp))

    return {
        "floor": floor,
        "room_id": room.room_id,
        "name": room.room_name,
        "space_type_id": getattr(room, "space_type_id", None),
        "zone_category": room.zone_category,
        "width_m": round(width, 2),
        "depth_m": round(depth, 2),
        "area_sqm": round(float(room.area_sqm), 2),
        "aspect": aspect,
        "stored_aspect": round(float(room.aspect_ratio or 0.0), 2),
        "stored_aspect_mismatch": abs(float(room.aspect_ratio or 0.0) - aspect) > 0.02,
        "span_class": "long" if aspect >= 2.5 else ("medium" if aspect >= 1.8 else "compact"),
        "band": band,
        "aspect_ok": (aspect <= band + 1e-6) if band else None,
        "min_area": min_area,
        "area_ok": (float(room.area_sqm) + 1e-6 >= min_area) if min_area else None,
        "min_width": min_width,
        "width_ok": (min(width, depth) + 1e-6 >= min_width) if min_width else None,
        "furniture_engine_ok": engine_ok,
        "furniture_geometry_ok": geo_ok,
        "furniture_ok": furniture_ok,
        "furniture_reasons": furn_reasons,
        "fixture_ok": fixture_ok,
        "fixture_count": len(room.fixtures),
        "applied_rules": list(room.applied_rules or []),
        "relaxation_rules": [str(rel.get("rule_id")) for rel in (room.relaxations or [])],
        "absorbed": "LAND-07-DEAD-CORNER-ABSORPTION" in (room.applied_rules or []),
        "outside_footprint_sqm": round(out_fp, 2),
        "outside_buildable_sqm": round(out_build, 2),
        "source": source_of(room.room_id, case["typology"], wings, room.applied_rules or ()),
    }


def main() -> int:
    global SLUG
    if "--slug" in sys.argv:
        SLUG = sys.argv[sys.argv.index("--slug") + 1]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    results: List[Dict[str, Any]] = []
